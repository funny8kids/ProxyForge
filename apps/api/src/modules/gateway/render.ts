import type { CompileWarning, ProxyProtocol } from '@proxyforge/contracts';
import type { CompileOutput } from '../policy/compiler.js';

/**
 * GOST v3 配置渲染。
 *
 * 设计约束：
 *   1. 一个策略 = 一个 service（一个监听端口），成员在 chains.nodes 里固化。
 *   2. 正式策略与实验策略**物理分离**：公开代理只能进独立的 lab 实例，
 *      在配置里用独立 chains 段 + 显式警告注释，不可能与正式成员混流。
 *   3. 渲染结果里的凭据一律脱敏（配置会进版本历史，明文落库等于泄露）。
 */

export interface RenderInput {
  instanceName: string;
  policies: CompileOutput[];
  warnings: CompileWarning[];
}

const CONNECTOR: Record<ProxyProtocol, string> = {
  HTTP: 'http',
  HTTPS_CONNECT: 'http',
  SOCKS4: 'socks4',
  SOCKS5: 'socks5',
};

const SELECTOR: Record<string, string> = {
  DIRECT: 'round',
  FIXED: 'fifo',
  FASTEST: 'round',
  WEIGHTED: 'round',
  STICKY: 'round',
  FAILOVER: 'round',
  REGION: 'round',
};

export function renderGatewayConfig(input: RenderInput): string {
  const lines: string[] = [];

  // 产物注释固定英文。
  // 这份文件是会被下发到机器、并且按内容哈希留档的不可变产物，
  // 它的语言不该随查看者的界面语言变化。人话解释在 API 的 warnings 字段里，
  // 界面按当前语言渲染；这里只留机器可读的 code 与计数。
  lines.push('# ============================================================');
  lines.push('# ProxyForge compiled artifact - do not edit by hand');
  lines.push('# Generated by the policy compiler; manual edits are overwritten on next compile.');
  lines.push(`# instance: ${input.instanceName}`);
  lines.push(`# policies: ${input.policies.length}`);
  lines.push(`# generated-at: ${new Date().toISOString()}`);
  lines.push('# ============================================================');

  if (input.warnings.length > 0) {
    lines.push('#');
    lines.push('# COMPILE WARNINGS');
    for (const w of input.warnings) {
      lines.push(`#   [${w.code}] count=${w.count ?? 0}`);
    }
  }

  const formal = input.policies.filter((p) => p.policy.members.length > 0);
  const experimental = input.policies.filter((p) => p.experimentalMembers.length > 0);

  lines.push('');
  lines.push('services:');

  if (formal.length === 0) {
    lines.push('  []');
  } else {
    for (const p of formal) {
      const svc = `svc-${p.policy.policyKey}`;
      const chain = `chain-${p.policy.policyKey}`;
      lines.push(`  - name: ${svc}`);
      lines.push(`    addr: ":${p.policy.listenPort}"`);
      lines.push('    handler:');
      lines.push('      type: http');
      lines.push(`      chain: ${chain}`);
      lines.push('    listener:');
      lines.push('      type: tcp');
      lines.push('    forwarder:');
      lines.push('      nodes:');
      for (const m of p.policy.members) {
        lines.push(`        - name: ${nodeName(m.endpointId)}`);
        lines.push(`          addr: ${m.host}:${m.port}`);
        lines.push('          connector:');
        lines.push(`            type: ${CONNECTOR[m.protocol]}`);
        lines.push('          dialer:');
        lines.push('            type: tcp');
      }
    }
  }

  lines.push('');
  lines.push('chains:');

  if (formal.length === 0) {
    lines.push('  []');
  } else {
    for (const p of formal) {
      lines.push(`  - name: chain-${p.policy.policyKey}`);
      lines.push('    hops:');
      lines.push('      - name: hop-0');
      lines.push('        selector:');
      lines.push(`          strategy: ${SELECTOR[p.policy.strategy] ?? 'round'}`);
      lines.push('          maxFails: 3');
      lines.push('          failTimeout: 30s');
      lines.push('        nodes:');
      for (const m of p.policy.members) {
        lines.push(`          - name: ${nodeName(m.endpointId)}`);
        lines.push(`            addr: ${m.host}:${m.port}`);
        lines.push('            connector:');
        lines.push(`              type: ${CONNECTOR[m.protocol]}`);
      }
    }
  }

  // ── 实验段：物理隔离，绝不与正式成员共用 chain ──
  if (experimental.length > 0) {
    lines.push('');
    lines.push('# ============================================================');
    lines.push('# EXPERIMENTAL ISOLATION - public proxies');
    lines.push('# Members below are PUBLIC_PROXY: by SEC-001 6.2 they may never enter the formal gateway.');
    lines.push('# They listen on a dedicated port, for connectivity experiments only, and carry no production traffic.');
    lines.push('# Reachability is not legitimacy: the authorization of these addresses has not been verified.');
    lines.push('# ============================================================');
    lines.push('  # lab-services:');
    for (const p of experimental) {
      const labPort = p.policy.listenPort + 1000;
      lines.push(`  #   - name: lab-${p.policy.policyKey}`);
      lines.push(`  #     addr: ":${labPort}"`);
      lines.push(`  #     chain: lab-chain-${p.policy.policyKey}`);
      lines.push(`  #     members: ${p.experimentalMembers.length} (public proxy, isolated)`);
    }
  }

  return `${lines.join('\n')}\n`;
}

/** 节点名用 id 前 8 位：稳定、可读、不泄露地址 */
function nodeName(endpointId: string): string {
  return `pf-${endpointId.replace(/-/g, '').slice(0, 8)}`;
}

export function configHash(content: string): string {
  // 稳定哈希：忽略 generated-at 这类「每次编译都会变、但不改变语义」的行。
  // 不排除它的话，每次编译都算出不同的 hash，去重永远不成立，
  // 于是 worker 每轮都插一条新版本 —— 版本号无限膨胀，历史里全是同一份配置。
  const stable = content
    .split('\n')
    .filter((line) => !line.startsWith('# generated-at:'))
    .join('\n');

  // 简单稳定哈希即可（用于版本比对，不是安全用途）
  let h1 = 0x811c9dc5;
  let h2 = 0x01000193;
  for (let i = 0; i < stable.length; i += 1) {
    const c = stable.charCodeAt(i);
    h1 = Math.imul(h1 ^ c, 0x01000193) >>> 0;
    h2 = Math.imul(h2 + c, 0x85ebca6b) >>> 0;
  }
  return `${h1.toString(16).padStart(8, '0')}${h2.toString(16).padStart(8, '0')}`;
}
